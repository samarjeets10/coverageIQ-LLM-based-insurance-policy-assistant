class ServiceDependencyUnavailableError(RuntimeError):
    """Base error mapped to HTTP 503 when a required backend dependency is down."""


class ModelUnavailableError(ServiceDependencyUnavailableError):
    """Raised when LightGBM artifacts are missing, unreadable, or schema-incompatible."""


class CatalogDatabaseUnavailableError(ServiceDependencyUnavailableError):
    """Raised when policy_attributes is absent or PostgreSQL retrieval fails."""


class UnsupportedRankingModelError(ValueError):
    """Raised when a caller requests an unimplemented ranking backend."""


class InferenceProcessingError(RuntimeError):
    """Raised on unexpected feature or prediction errors after eligibility filtering."""


class CatalogIntegrityError(InferenceProcessingError):
    """Raised when retrieved catalog records violate uniqueness or structural invariants."""


