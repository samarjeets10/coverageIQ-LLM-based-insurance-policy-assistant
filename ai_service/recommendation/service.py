def _build_profile_completeness(
    profile: UserProfileRequest,
    *,
    backend_used: Literal["lightgbm", "weighted"],
) -> ProfileCompleteness:
    """Represent omitted optional profile fields explicitly without fabricating values."""
    missing_fields: list[str] = []
    assumptions: dict[str, Any] = {}

    if profile.annual_income_inr is None:
        missing_fields.append("annual_income_inr")
        assumptions["annual_income_inr"] = (
            "encoded_as_0_with_has_annual_income_0_indicator"
            if backend_used == "lightgbm"
            else "omitted_ignored_by_weighted_scorer"
        )

    if profile.risk_preference is None:
        missing_fields.append("risk_preference")
        assumptions["risk_preference"] = "defaulted_to_balanced"

    return ProfileCompleteness(
        is_complete=len(missing_fields) == 0,
        missing_fields=missing_fields,
        applied_assumptions=assumptions,
        income_distribution_mismatch_risk=(
            profile.annual_income_inr is None and backend_used == "lightgbm"
        ),
    )


def _build_profile_limitation_warnings(
    profile: UserProfileRequest,
    metadata: Mapping[str, Any] | None,
    *,
    backend_used: Literal["lightgbm", "weighted"] = "lightgbm",
) -> list[str]:
    """Build explicit limitation and missing-personalization warnings."""
    warnings: list[str] = []

    if backend_used == "weighted":
        warnings.append(WEIGHTED_FALLBACK_LIMITATION_NOTE)
    else:
        disclaimer = str((metadata or {}).get("synthetic_data_disclaimer") or "").strip()
        warnings.append(disclaimer if disclaimer else SYNTHETIC_MODEL_LIMITATION_NOTE)

    if profile.annual_income_inr is None:
        if backend_used == "weighted":
            warnings.append(
                "Optional profile field 'annual_income_inr' was omitted; Stage 5 encoded "
                "annual_income=0.0 with has_annual_income=0.0, and weighted scoring places "
                "zero weight on annual income."
            )
        else:
            warnings.append(
                "Optional profile field 'annual_income_inr' was omitted; Stage 5 encoded "
                "annual_income=0.0 with has_annual_income=0.0, whereas Stage 6 synthetic "
                "training profiles all had positive income."
            )
    if profile.risk_preference is None:
        warnings.append(
            "Optional profile field 'risk_preference' was omitted; Stage 5 assumed "
            "'balanced' rather than a user-specified ranking preference."
        )
    return warnings


def _validate_loaded_model_state(model_state: ModelState) -> tuple[lgb.LGBMRanker, dict[str, Any]]:
    """Verify cached ModelState holds an initialized, schema-compatible ranker."""
    if not model_state.is_ready:
        raise ModelUnavailableError(model_state.error_message or "Ranking model is not available.")

    assert model_state.model is not None and model_state.metadata is not None
    metadata = model_state.metadata
    saved_version = str(metadata.get("feature_schema_version") or "")
    saved_columns = tuple(metadata.get("feature_columns") or ())

    if saved_version != FEATURE_SCHEMA_VERSION:
        raise ModelUnavailableError(
            f"Model feature schema version mismatch: expected {FEATURE_SCHEMA_VERSION}, "
            f"got {saved_version or 'unknown'}."
        )
    if saved_columns != FEATURE_COLUMNS:
        raise ModelUnavailableError(
            "Model feature columns do not match the active 59-column feature schema."
        )
    return model_state.model, metadata


def _extract_factual_highlights(policy: Mapping[str, Any]) -> list[str]:
    """Assemble factual policy highlights strictly from non-null DB fields."""
    highlights: list[str] = []

    if policy.get("cashless_available") is True:
        hospitals = policy.get("network_hospitals_count")
        if hospitals is not None and int(hospitals) > 0:
            highlights.append(f"Cashless network: {int(hospitals):,} hospitals/garages")
        else:
            highlights.append("Cashless claim facility available")

    csr = policy.get("claim_settlement_ratio")
    if csr is not None:
        highlights.append(f"Claim settlement ratio: {float(csr):.2f}%")

    if policy.get("lifelong_renewal") is True:
        highlights.append("Lifelong renewal supported")

    if policy.get("restoration_benefit") is True:
        highlights.append("Sum insured restoration benefit")

    if policy.get("ped_covered") is True and str(policy.get("policy_type", "")).lower() == "health":
        ped_wait = policy.get("ped_waiting_period_months")
        if ped_wait is not None:
            highlights.append(f"PED covered ({int(ped_wait)}-month waiting period)")
        else:
            highlights.append("Pre-existing conditions covered")

    if policy.get("pan_india_coverage") is True:
        highlights.append("Pan-India coverage")

    copay = policy.get("copay_pct")
    if copay is not None and float(copay) == 0.0:
        highlights.append("Zero co-payment")

    return highlights


def _build_feature_breakdown(feature_row: pd.Series) -> dict[str, float]:
    """Return finite curated numeric features computed by Stage 5 for transparency."""
    breakdown: dict[str, float] = {}
    for col in _KEY_FEATURE_BREAKDOWN_COLUMNS:
        val = float(feature_row[col])
        if math.isfinite(val):
            breakdown[col] = round(val, 4)
    return breakdown


def _validate_feature_frame_ready_for_scoring(
    feature_matrix: pd.DataFrame,
    expected_rows: int,
) -> None:
    """Validate Stage 5 output shape, schema ordering, and finiteness before inference."""
    if tuple(feature_matrix.columns) != FEATURE_COLUMNS:
        raise InferenceProcessingError(
            "Engineered feature matrix columns do not match active FEATURE_COLUMNS schema."
        )
    if len(feature_matrix) != expected_rows:
        raise InferenceProcessingError(
            f"Feature matrix row count ({len(feature_matrix)}) does not match eligible "
            f"policy count ({expected_rows})."
        )
    if expected_rows > 0:
        values = feature_matrix.to_numpy(dtype=np.float64)
        if not np.isfinite(values).all():
            raise InferenceProcessingError(
                "Engineered feature matrix contains non-finite (NaN/Inf) values."
            )


def _load_catalog_candidates(conn: Connection, policy_type: str) -> list[dict[str, Any]]:
    """Load catalog candidates pushing policy_type down to SQL when supported."""
    loader = load_catalog_policies_from_db
    try:
        params = inspect.signature(loader).parameters
    except (TypeError, ValueError):
        params = {}
    if "policy_type" in params:
        return loader(conn, policy_type=policy_type, active_only=False)
    return loader(conn, active_only=False)


def _resolve_top_n_citations(
    citation_provider: RecommendationCitationProvider | None,
    ranked_indices: Sequence[int],
    eligible_policies: Sequence[Mapping[str, Any]],
    raw_scores: np.ndarray,
    *,
    model_used: str,
    request_id: str,
    scope: TrustedScope | None = None,
) -> dict[str, list[dict[str, Any]]]:
    """Fetch validated citations for ranked Top-N policies through the citation interface."""
    provider = citation_provider if citation_provider is not None else NullCitationProvider()
    requests: list[PolicyCitationRequest] = []
    for rank_num, orig_idx in enumerate(ranked_indices, start=1):
        pol = eligible_policies[orig_idx]
        pv_id = pol.get("policy_version_id")
        requests.append(
            PolicyCitationRequest(
                policy_id=str(pol["policy_id"]),
                policy_version_id=str(pv_id) if pv_id is not None else None,
                policy_name=str(pol.get("policy_name") or pol.get("name") or "Unnamed Policy"),
                policy_type=str(pol["policy_type"]).strip().lower(),
                rank=rank_num,
                score=float(raw_scores[orig_idx]),
                model_used=model_used,
                key_highlights=tuple(_extract_factual_highlights(pol)),
                scope=scope,
            )
        )

    citations_by_policy = provider.get_citations(requests, request_id=request_id)
    if not isinstance(citations_by_policy, Mapping):
        raise InferenceProcessingError("Citation provider must return a mapping by policy_id.")

    validated: dict[str, list[dict[str, Any]]] = {}
    for req in requests:
        entries = citations_by_policy.get(req.policy_id, [])
        if not isinstance(entries, list):
            raise InferenceProcessingError(
                "Citation provider returned invalid citation entries for policy."
            )
        normalized_entries: list[dict[str, Any]] = []
        for item in entries:
            try:
                normalized_entries.append(normalize_and_validate_citation(item))
            except ValueError as exc:
                raise InferenceProcessingError(
                    "Citation provider returned invalid citation entries for policy."
                ) from exc
        validated[req.policy_id] = normalized_entries
    return validated


def _round_timings(timings_ms: Mapping[str, float]) -> dict[str, float]:
    """Round sub-stage latency metrics deterministically for structured logs."""
    return {key: round(float(val), 3) for key, val in timings_ms.items()}


