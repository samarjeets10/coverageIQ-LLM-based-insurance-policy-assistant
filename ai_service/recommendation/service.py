@dataclass(frozen=True)
class ModelState:
    """Cached LightGBM model state initialized once during application startup."""

    model: lgb.LGBMRanker | None
    metadata: dict[str, Any] | None
    artifacts_dir: Path
    error_message: str | None = None
    error_kind: Literal["missing", "incompatible", "corrupt", "load_failed"] | None = None
    warmed_up: bool = False

    @property
    def is_ready(self) -> bool:
        """Return True only when both model and schema-validated metadata loaded cleanly."""
        return self.model is not None and self.metadata is not None and self.error_message is None

    @property
    def model_name(self) -> str:
        """Return loaded model identifier without guessing."""
        if self.metadata is not None and self.metadata.get("model_name"):
            return str(self.metadata["model_name"])
        return MODEL_NAME

    @property
    def model_version(self) -> str | None:
        """Return loaded semantic model version if available."""
        if self.metadata is not None and self.metadata.get("model_version"):
            return str(self.metadata["model_version"])
        return None

    @property
    def feature_schema_version(self) -> str | None:
        """Return validated feature schema version recorded in model metadata."""
        if self.metadata is not None and self.metadata.get("feature_schema_version"):
            return str(self.metadata["feature_schema_version"])
        return None


def _warm_up_lightgbm_model(model: lgb.LGBMRanker) -> None:
    """Execute one finite synthetic forward pass at startup to catch broken boosters early."""
    warm_df = pd.DataFrame(
        np.zeros((1, len(FEATURE_COLUMNS)), dtype=np.float64),
        columns=list(FEATURE_COLUMNS),
    )
    scores = np.asarray(model.predict(warm_df), dtype=np.float64)
    if len(scores) != 1 or not np.isfinite(scores).all():
        raise IncompatibleModelError("Ranking model warm-up returned non-finite or invalid scores.")


def load_model_state(model_dir: Path | str | None = None) -> ModelState:
    """Load, schema-validate, and warm up Stage 6 LightGBM artifacts into ModelState.

    Captures missing, corrupt, incompatible, or unfitted artifact failures without
    crashing FastAPI startup so health endpoints remain operational while LightGBM
    recommendation requests return controlled HTTP 503 responses.
    """
    resolved_dir = Path(model_dir) if model_dir is not None else DEFAULT_ARTIFACTS_DIR
    try:
        model, metadata = load_model(resolved_dir)
    except FileNotFoundError as exc:
        logger.error("Ranking model artifacts missing under %s: %s", resolved_dir, exc)
        return ModelState(
            model=None,
            metadata=None,
            artifacts_dir=resolved_dir,
            error_message="Ranking model artifacts are unavailable.",
            error_kind="missing",
            warmed_up=False,
        )
    except IncompatibleModelError as exc:
        logger.error("Ranking model schema incompatibility in %s: %s", resolved_dir, exc)
        return ModelState(
            model=None,
            metadata=None,
            artifacts_dir=resolved_dir,
            error_message=f"Ranking model is incompatible with active feature schema: {exc}",
            error_kind="incompatible",
            warmed_up=False,
        )
    except (
        json.JSONDecodeError,
        EOFError,
        zlib.error,
        pickle.UnpicklingError,
        AttributeError,
        ModuleNotFoundError,
        KeyError,
        TypeError,
        ValueError,
    ) as exc:
        logger.error("Corrupt or unreadable ranking model artifact in %s: %s", resolved_dir, exc)
        return ModelState(
            model=None,
            metadata=None,
            artifacts_dir=resolved_dir,
            error_message="Ranking model artifacts are corrupt or unreadable.",
            error_kind="corrupt",
            warmed_up=False,
        )
    except (OSError, RuntimeError):
        logger.exception(
            "Unexpected I/O or runtime error loading ranking model from %s", resolved_dir
        )
        return ModelState(
            model=None,
            metadata=None,
            artifacts_dir=resolved_dir,
            error_message="Ranking model failed to initialize.",
            error_kind="load_failed",
            warmed_up=False,
        )

    try:
        _warm_up_lightgbm_model(model)
    except (IncompatibleModelError, FeatureSchemaValidationError) as exc:
        logger.error("Ranking model warm-up failed schema check in %s: %s", resolved_dir, exc)
        return ModelState(
            model=None,
            metadata=None,
            artifacts_dir=resolved_dir,
            error_message=f"Ranking model is incompatible with active feature schema: {exc}",
            error_kind="incompatible",
            warmed_up=False,
        )
    except (lgb.basic.LightGBMError, ValueError, RuntimeError, TypeError, OSError) as exc:
        logger.error("Ranking model warm-up failed in %s: %s", resolved_dir, exc)
        return ModelState(
            model=None,
            metadata=None,
            artifacts_dir=resolved_dir,
            error_message="Ranking model failed startup warm-up validation.",
            error_kind="load_failed",
            warmed_up=False,
        )

    return ModelState(
        model=model,
        metadata=metadata,
        artifacts_dir=resolved_dir,
        warmed_up=True,
    )


