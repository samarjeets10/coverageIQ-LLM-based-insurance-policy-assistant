def recommend_policies_for_request(
    request: RecommendRequest,
    conn: Connection,
    model_state: ModelState,
    *,
    request_id: str | None = None,
    weighted_config: WeightedScoringConfig | None = None,
    citation_provider: RecommendationCitationProvider | None = None,
) -> RecommendResponse:
    """Run the full Stage 4 -> Stage 5 -> Stage 6 / Weighted recommendation inference flow."""
    resolved_request_id = request_id or str(uuid.uuid4())
    t_total_start = time.perf_counter()
    timings_ms: dict[str, float] = {
        "db": 0.0,
        "filter": 0.0,
        "features": 0.0,
        "scoring": 0.0,
        "citations": 0.0,
        "total": 0.0,
    }

    # Step 1: Validate requested ranking backend explicitly (never silently substitute)
    if request.ranking_model == "xgboost":
        emit_structured_event(
            logger,
            level=logging.WARNING,
            event="recommendation.unsupported_model",
            message="Requested ranking model is not implemented.",
            request_id=resolved_request_id,
            policy_type=request.profile.policy_type,
            ranking_model_requested=request.ranking_model,
        )
        raise UnsupportedRankingModelError(
            "Ranking model 'xgboost' is not implemented in Stage 9A; "
            "supported options are 'auto', 'lightgbm', and 'weighted'."
        )
    if request.ranking_model not in ("auto", "lightgbm", "weighted"):
        raise UnsupportedRankingModelError(
            f"Ranking model '{request.ranking_model}' is not supported; "
            "supported options are 'auto', 'lightgbm', and 'weighted'."
        )

    backend_used: Literal["lightgbm", "weighted"]
    model: lgb.LGBMRanker | None
    metadata: dict[str, Any] | None
    if request.ranking_model == "weighted":
        backend_used = "weighted"
        model = None
        metadata = None
        model_name = WEIGHTED_SCORER_NAME
        model_version = WEIGHTED_SCORER_VERSION
        schema_version = FEATURE_SCHEMA_VERSION
    else:
        backend_used = "lightgbm"
        try:
            model, metadata = _validate_loaded_model_state(model_state)
        except ModelUnavailableError:
            emit_structured_event(
                logger,
                level=logging.WARNING,
                event="recommendation.model_unavailable",
                message="LightGBM ranking model is unavailable for request.",
                request_id=resolved_request_id,
                policy_type=request.profile.policy_type,
                ranking_model_requested=request.ranking_model,
                error_kind=model_state.error_kind or "unavailable",
            )
            raise
        model_name = str(metadata.get("model_name") or MODEL_NAME)
        model_version = str(metadata.get("model_version") or MODEL_VERSION)
        schema_version = str(metadata.get("feature_schema_version") or FEATURE_SCHEMA_VERSION)

    # Step 2: Retrieve real candidate catalog policies from PostgreSQL
    t_db_start = time.perf_counter()
    try:
        candidate_policies = _load_catalog_candidates(conn, request.profile.policy_type)
    except PolicyAttributesTableUnavailableError as exc:
        timings_ms["db"] = (time.perf_counter() - t_db_start) * 1000.0
        timings_ms["total"] = (time.perf_counter() - t_total_start) * 1000.0
        emit_structured_event(
            logger,
            level=logging.WARNING,
            event="recommendation.db_unavailable",
            message="Required catalog table unavailable during recommendation.",
            request_id=resolved_request_id,
            policy_type=request.profile.policy_type,
            ranking_model_requested=request.ranking_model,
            model_used=model_name,
            latency_ms=_round_timings(timings_ms),
        )
        raise CatalogDatabaseUnavailableError(
            "Policy catalog attributes table ('policy_attributes') is not available in PostgreSQL."
        ) from exc
    except DuplicateCatalogPolicyError as exc:
        timings_ms["db"] = (time.perf_counter() - t_db_start) * 1000.0
        timings_ms["total"] = (time.perf_counter() - t_total_start) * 1000.0
        emit_structured_event(
            logger,
            level=logging.ERROR,
            event="recommendation.catalog_integrity_error",
            message="Duplicate current-version policy attributes detected in catalog.",
            request_id=resolved_request_id,
            policy_type=request.profile.policy_type,
            ranking_model_requested=request.ranking_model,
            model_used=model_name,
            latency_ms=_round_timings(timings_ms),
        )
        raise CatalogIntegrityError(
            "Catalog integrity error: duplicate current-version attribute rows detected."
        ) from exc
    except SQLAlchemyError as exc:
        timings_ms["db"] = (time.perf_counter() - t_db_start) * 1000.0
        timings_ms["total"] = (time.perf_counter() - t_total_start) * 1000.0
        emit_structured_event(
            logger,
            level=logging.ERROR,
            event="recommendation.db_query_failed",
            message="Catalog query failed during recommendation.",
            request_id=resolved_request_id,
            policy_type=request.profile.policy_type,
            ranking_model_requested=request.ranking_model,
            model_used=model_name,
            error_type=type(exc).__name__,
            latency_ms=_round_timings(timings_ms),
        )
        raise CatalogDatabaseUnavailableError(
            "Failed to retrieve candidate policies from PostgreSQL."
        ) from exc
    except (ValueError, TypeError) as exc:
        timings_ms["db"] = (time.perf_counter() - t_db_start) * 1000.0
        timings_ms["total"] = (time.perf_counter() - t_total_start) * 1000.0
        emit_structured_event(
            logger,
            level=logging.ERROR,
            event="recommendation.catalog_data_error",
            message="Catalog attribute retrieval encountered malformed policy metadata.",
            request_id=resolved_request_id,
            policy_type=request.profile.policy_type,
            ranking_model_requested=request.ranking_model,
            model_used=model_name,
            error_type=type(exc).__name__,
            latency_ms=_round_timings(timings_ms),
        )
        raise CatalogIntegrityError(
            "Catalog attribute retrieval encountered malformed policy metadata."
        ) from exc
    timings_ms["db"] = (time.perf_counter() - t_db_start) * 1000.0

    # Step 3: Deterministic hard filtering (MUST execute before feature engineering & scoring)
    t_filter_start = time.perf_counter()
    try:
        filter_result = filter_policies(request.profile, candidate_policies)
    except DuplicateCatalogPolicyError as exc:
        timings_ms["filter"] = (time.perf_counter() - t_filter_start) * 1000.0
        timings_ms["total"] = (time.perf_counter() - t_total_start) * 1000.0
        emit_structured_event(
            logger,
            level=logging.ERROR,
            event="recommendation.catalog_integrity_error",
            message="Duplicate policy_id rows detected during eligibility filtering.",
            request_id=resolved_request_id,
            policy_type=request.profile.policy_type,
            ranking_model_requested=request.ranking_model,
            model_used=model_name,
            latency_ms=_round_timings(timings_ms),
        )
        raise CatalogIntegrityError(
            "Catalog integrity error: duplicate policy_id entries detected in catalog."
        ) from exc
    except (MissingMandatoryProfileError, ValueError, TypeError) as exc:
        timings_ms["filter"] = (time.perf_counter() - t_filter_start) * 1000.0
        timings_ms["total"] = (time.perf_counter() - t_total_start) * 1000.0
        emit_structured_event(
            logger,
            level=logging.ERROR,
            event="recommendation.filter_error",
            message="Hard eligibility filtering encountered malformed input data.",
            request_id=resolved_request_id,
            policy_type=request.profile.policy_type,
            ranking_model_requested=request.ranking_model,
            model_used=model_name,
            error_type=type(exc).__name__,
            latency_ms=_round_timings(timings_ms),
        )
        raise InferenceProcessingError(
            "Failed to evaluate deterministic eligibility filters on catalog records."
        ) from exc
    timings_ms["filter"] = (time.perf_counter() - t_filter_start) * 1000.0

    profile_completeness = _build_profile_completeness(request.profile, backend_used=backend_used)
    warnings = _build_profile_limitation_warnings(
        request.profile, metadata, backend_used=backend_used
    )

    # Step 4: Explicit zero-match handling — never pass empty or ineligible sets to scoring
    if filter_result.status == "NO_MATCHING_POLICIES" or not filter_result.eligible_policies:
        if filter_result.filter_report.total_candidates == 0:
            warnings.append("No catalog policies are currently present for eligibility evaluation.")
        else:
            warnings.append(
                "No candidate policies passed deterministic hard eligibility rules; "
                "feature engineering and ranking scoring were skipped."
            )
        timings_ms["total"] = (time.perf_counter() - t_total_start) * 1000.0
        emit_structured_event(
            logger,
            level=logging.INFO,
            event="recommendation.no_match",
            message="Recommendation completed with zero eligible policies.",
            request_id=resolved_request_id,
            policy_type=request.profile.policy_type,
            ranking_model_requested=request.ranking_model,
            model_used=model_name,
            status="NO_MATCHING_POLICIES",
            total_candidates=filter_result.filter_report.total_candidates,
            eligible_count=0,
            rejected_count=filter_result.filter_report.eliminated_count,
            returned_count=0,
            profile_is_complete=profile_completeness.is_complete,
            missing_profile_fields=profile_completeness.missing_fields,
            latency_ms=_round_timings(timings_ms),
        )
        return RecommendResponse(
            request_id=resolved_request_id,
            status="NO_MATCHING_POLICIES",
            recommendations=[],
            filter_report=filter_result.filter_report,
            model_used=model_name,
            model_version=model_version,
            feature_schema_version=schema_version,
            warnings=warnings,
            profile_completeness=profile_completeness,
        )

    eligible_policies = filter_result.eligible_policies

    # Step 5: Stage 5 deterministic feature extraction for eligible candidates only
    t_feat_start = time.perf_counter()
    try:
        feature_matrix = build_feature_matrix(request.profile, eligible_policies)
        _validate_feature_frame_ready_for_scoring(feature_matrix, len(eligible_policies))
    except (
        MissingMandatoryFeatureInputError,
        FeatureSchemaValidationError,
        ValueError,
    ) as exc:
        timings_ms["features"] = (time.perf_counter() - t_feat_start) * 1000.0
        timings_ms["total"] = (time.perf_counter() - t_total_start) * 1000.0
        emit_structured_event(
            logger,
            level=logging.ERROR,
            event="recommendation.feature_error",
            message="Feature engineering failed during inference.",
            request_id=resolved_request_id,
            policy_type=request.profile.policy_type,
            ranking_model_requested=request.ranking_model,
            model_used=model_name,
            error_type=type(exc).__name__,
            latency_ms=_round_timings(timings_ms),
        )
        raise InferenceProcessingError(
            "Failed to construct valid 59-column feature matrix for eligible policies."
        ) from exc
    timings_ms["features"] = (time.perf_counter() - t_feat_start) * 1000.0

    # Step 6: Execute selected ranking backend (LightGBM OR explicit weighted fallback)
    t_score_start = time.perf_counter()
    weighted_breakdowns: list[dict[str, float]] | None = None
    try:
        if backend_used == "weighted":
            weighted_res = score_policies_weighted(feature_matrix, config=weighted_config)
            raw_scores = weighted_res.scores
            weighted_breakdowns = weighted_res.dimension_breakdowns
        else:
            assert model is not None
            raw_scores = predict_ranking_scores(model, feature_matrix)
    except (FeatureSchemaValidationError, lgb.basic.LightGBMError, ValueError, RuntimeError) as exc:
        timings_ms["scoring"] = (time.perf_counter() - t_score_start) * 1000.0
        timings_ms["total"] = (time.perf_counter() - t_total_start) * 1000.0
        emit_structured_event(
            logger,
            level=logging.ERROR,
            event="recommendation.scoring_error",
            message="Ranking scoring failed on engineered feature matrix.",
            request_id=resolved_request_id,
            policy_type=request.profile.policy_type,
            ranking_model_requested=request.ranking_model,
            model_used=model_name,
            error_type=type(exc).__name__,
            latency_ms=_round_timings(timings_ms),
        )
        raise InferenceProcessingError(
            f"{model_name} ranking prediction failed on engineered feature matrix."
        ) from exc
    timings_ms["scoring"] = (time.perf_counter() - t_score_start) * 1000.0

    if len(raw_scores) != len(eligible_policies) or not np.isfinite(raw_scores).all():
        raise InferenceProcessingError("Ranking model returned invalid or non-finite scores.")

    # Step 7: Sort strictly descending by score (deterministic tie-break on policy_id)
    ranked_indices = sorted(
        range(len(eligible_policies)),
        key=lambda idx: (-float(raw_scores[idx]), str(eligible_policies[idx].get("policy_id", ""))),
    )
    top_indices = ranked_indices[: request.top_n]

    # Step 8: Citation interface seam (NullCitationProvider returns [] in Stage 9A)
    t_cit_start = time.perf_counter()
    try:
        citations_by_policy = _resolve_top_n_citations(
            citation_provider,
            top_indices,
            eligible_policies,
            raw_scores,
            model_used=model_name,
            request_id=resolved_request_id,
            scope=request.scope,
        )
    except InferenceProcessingError:
        raise
    except (OSError, ValueError, TypeError, RuntimeError) as exc:
        timings_ms["citations"] = (time.perf_counter() - t_cit_start) * 1000.0
        timings_ms["total"] = (time.perf_counter() - t_total_start) * 1000.0
        emit_structured_event(
            logger,
            level=logging.ERROR,
            event="recommendation.citation_error",
            message="Citation provider failed unexpectedly.",
            request_id=resolved_request_id,
            policy_type=request.profile.policy_type,
            ranking_model_requested=request.ranking_model,
            model_used=model_name,
            error_type=type(exc).__name__,
            latency_ms=_round_timings(timings_ms),
        )
        raise InferenceProcessingError("Failed to resolve citations for recommendations.") from exc
    timings_ms["citations"] = (time.perf_counter() - t_cit_start) * 1000.0

    recommendations: list[RecommendedPolicy] = []
    for rank_num, orig_idx in enumerate(top_indices, start=1):
        pol = eligible_policies[orig_idx]
        policy_id = str(pol["policy_id"])
        raw_pv_id = pol.get("policy_version_id")
        feature_row = feature_matrix.iloc[orig_idx]
        breakdown = _build_feature_breakdown(feature_row)
        if weighted_breakdowns is not None:
            breakdown.update(weighted_breakdowns[orig_idx])

        recommendations.append(
            RecommendedPolicy(
                policy_id=policy_id,
                policy_version_id=str(raw_pv_id) if raw_pv_id is not None else None,
                policy_name=str(pol.get("policy_name") or pol.get("name") or "Unnamed Policy"),
                insurer_name=(
                    str(pol["insurer_name"]) if pol.get("insurer_name") is not None else None
                ),
                policy_type=str(pol["policy_type"]).strip().lower(),
                rank=rank_num,
                score=float(raw_scores[orig_idx]),
                model_used=model_name,
                annual_premium_min=float(pol["annual_premium_min"]),
                annual_premium_max=float(pol["annual_premium_max"]),
                sum_insured_max=float(pol["sum_insured_max"]),
                key_highlights=_extract_factual_highlights(pol),
                feature_breakdown=breakdown,
                citations=citations_by_policy.get(policy_id, []),
            )
        )

    timings_ms["total"] = (time.perf_counter() - t_total_start) * 1000.0
    emit_structured_event(
        logger,
        level=logging.INFO,
        event="recommendation.completed",
        message="Recommendation completed.",
        request_id=resolved_request_id,
        policy_type=request.profile.policy_type,
        ranking_model_requested=request.ranking_model,
        model_used=model_name,
        status="RECOMMENDATIONS_READY",
        total_candidates=filter_result.filter_report.total_candidates,
        eligible_count=len(eligible_policies),
        rejected_count=filter_result.filter_report.eliminated_count,
        returned_count=len(recommendations),
        profile_is_complete=profile_completeness.is_complete,
        missing_profile_fields=profile_completeness.missing_fields,
        scope_present=request.scope is not None,
        scope_role=request.scope.role if request.scope else None,
        latency_ms=_round_timings(timings_ms),
    )

    return RecommendResponse(
        request_id=resolved_request_id,
        status="RECOMMENDATIONS_READY",
        recommendations=recommendations,
        filter_report=filter_result.filter_report,
        model_used=model_name,
        model_version=model_version,
        feature_schema_version=schema_version,
        warnings=warnings,
        profile_completeness=profile_completeness,
    )
